"""Write the Apps Script that builds the clinician survey as a Google Form.

The questions come from the running app's own /survey/questions (model B
hidden), so the Form asks exactly what the in-app form asks, in the same
order and words. Run:

    curl -s localhost:8000/survey/questions > form.json
    python3 tools/google_form/build_form_script.py form.json [FORM_ID] \
        > tools/google_form/create_survey_form.gs

then paste the .gs into script.google.com and run one function:
  createSurveyForm()  -- a new Form plus its response Sheet;
  updateSurveyForm()  -- rebuild the items of the Form FORM_ID in place, so
                         its link and its Sheet stay the same.

The Form shows no question ids (clinicians found "[Q4]" clutter); the
column -> app question id mapping is written next to the script, as
form_question_ids.md, for scoring the response Sheet.
"""

import json
import sys
from pathlib import Path

form = json.load(open(sys.argv[1]))
form_id = sys.argv[2] if len(sys.argv) > 2 else ""
labels = form["scale"]["labels"]

# Dropped from the Form: 19 asks how easy correcting the AI was, and the
# clinicians on the view-only box cannot correct anything.
SKIP_IDS = {19}
questions = [q for q in form["questions"] if q["id"] not in SKIP_IDS]

# Two lines: the first draft's five read as a wall of rules. Required
# questions need no note -- Google Forms marks them with * itself.
INTRO = (
    "Khoảng 5 phút, trả lời một lần sau khi xem xong các ca mẫu.\n"
    "Phiếu ẩn danh, không cần đăng nhập. Không có đúng hay sai: đánh giá thấp cũng có ích."
)


GRID_TITLE = "AI chấm đúng tới mức nào, với từng loại bất thường?"
# Not required: a clinician may not read every one of these findings, and a
# blank is worth more than a guess.
GRID_HELP = (
    "Không bắt buộc. Bác sĩ chỉ chấm những loại bất thường mình chắc chắn, "
    "hàng nào không chắc thì để trống."
)

ROW_HELP = "Chọn một ô cho mỗi hàng."


def js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def part_title(title: str) -> str:
    # "Phần 1. Kết quả AI: ..." -> "PHẦN 1. KẾT QUẢ AI: ...": Forms has no
    # bold or colour for titles, so capitals are what sets a part apart
    # from the groups inside it.
    return title.upper()


lines: list[str] = []
emit = lines.append
mapping: list[str] = []

emit("// Generated by tools/google_form/build_form_script.py -- do not edit by hand.")
emit("// Paste into https://script.google.com and run ONE function:")
emit("//   createSurveyForm() -- a new Form and its response Sheet;")
emit("//   updateSurveyForm() -- rebuild the existing Form in place (same link, same Sheet).")
emit("// Anonymous: no email collected, no Google sign-in required, name optional.")
emit(f"var FORM_ID = {js(form_id)};")
emit(f"var LABELS = {js(labels)};")
emit("")
emit("function addItems(form) {")
emit("  form.setTitle('Phiếu đánh giá phần mềm Spine Labeling');")
emit(f"  form.setDescription({js(INTRO)});")
emit("  form.setCollectEmail(false);")
emit("  form.setProgressBar(true);")
emit("  form.setConfirmationMessage('Cảm ơn bác sĩ đã dành thời gian đánh giá!');")
emit("  function scale(title, required) {")
emit("    form.addScaleItem().setTitle(title)")
emit("      .setBounds(1, 5).setLabels(LABELS[0], LABELS[4]).setRequired(required);")
emit("  }")

# Every part is its own Forms section (a page break): the section title is
# the one heading Forms draws as a coloured bar, so the three parts read as
# parts. Groups inside a part stay plain headers.
for sec in form["sections"]:
    emit(f"  form.addPageBreakItem().setTitle({js(part_title(sec['title']))});")
    for group in sec["groups"]:
        in_group = [q for q in questions if q["group"] == group]
        if not in_group:
            continue
        # All required: with three clinicians, one blank is a third of that
        # question's data.
        if len(in_group) == 1:
            q = in_group[0]
            emit(f"  scale({js(q['text'])}, true);")
            mapping.append(f"| {q['text']} | {q['id']} |")
            continue
        # A group of questions on the same 1-5 scale is one grid, a row per
        # question: fifteen full-width scale blocks made the Form read as
        # far longer than its twenty-odd answers. Column headings are the
        # words alone; "1 · Rất kém" read as two things.
        is_labels = all(q["matrix"] for q in in_group)
        title = GRID_TITLE if is_labels else group
        help_text = GRID_HELP if is_labels else ROW_HELP
        emit(f"  form.addGridItem().setTitle({js(title)})")
        emit(f"    .setHelpText({js(help_text)})")
        emit(f"    .setRows({js([q['text'] for q in in_group])})")
        emit(f"    .setColumns({js(labels)})")
        emit(f"    .setRequired({'false' if is_labels else 'true'});")
        for q in in_group:
            mapping.append(f"| {title} [{q['text']}] | {q['id']} |")

emit("  form.addPageBreakItem().setTitle('GÓP Ý VÀ THÔNG TIN NGƯỜI ĐÁNH GIÁ');")
emit("  form.addParagraphTextItem().setTitle('Bác sĩ có góp ý gì thêm cho phần mềm không?')")
emit("    .setHelpText('Ví dụ: ca nào AI chấm sai, chỗ nào khó dùng hay khó hiểu, cần thêm tính năng gì...');")
emit("  form.addTextItem().setTitle('Họ tên (có thể để trống)')")
emit("    .setHelpText('Không bắt buộc. Để trống thì phiếu ẩn danh.');")
emit("  form.addTextItem().setTitle('Chuyên khoa / vị trí (có thể để trống)');")
emit("}")
emit("")
emit("function createSurveyForm() {")
emit("  var form = FormApp.create('Phiếu đánh giá phần mềm Spine Labeling');")
emit("  addItems(form);")
emit("  var sheet = SpreadsheetApp.create('Phiếu đánh giá Spine Labeling (câu trả lời)');")
emit("  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());")
emit("  Logger.log('Form to send:   ' + form.getPublishedUrl());")
emit("  Logger.log('Form editor:    ' + form.getEditUrl());")
emit("  Logger.log('Responses sheet: ' + sheet.getUrl());")
emit("}")
emit("")
emit("function updateSurveyForm() {")
emit("  var form = FormApp.openById(FORM_ID);")
emit("  if (form.getResponses().length > 0) {")
emit("    throw new Error('Form already has responses: delete them first (Responses tab), or the Sheet mixes old and new questions.');")
emit("  }")
emit("  form.getItems().forEach(function (item) { form.deleteItem(item); });")
emit("  addItems(form);")
emit("  Logger.log('Updated. Form to send: ' + form.getPublishedUrl());")
emit("}")
print("\n".join(lines))

Path(__file__).with_name("form_question_ids.md").write_text(
    "# Google Form column -> app question id\n\n"
    "Generated by build_form_script.py. Use it to score the response Sheet\n"
    "with the same ids as the in-app survey (backend/app/survey_questions.py).\n\n"
    "| Form question (Sheet column) | App id |\n|---|---|\n" + "\n".join(mapping) + "\n"
)
