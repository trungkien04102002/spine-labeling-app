"""Write the Apps Script that creates the clinician survey as a Google Form.

The questions come from the running app's own /survey/questions (model B
hidden), so the Form asks exactly what the in-app form asks, in the same
order and words. Run:

    curl -s localhost:8000/survey/questions > form.json
    python3 tools/google_form/build_form_script.py form.json > tools/google_form/create_survey_form.gs

then paste the .gs into script.google.com and run createSurveyForm() once.
Each item's description ends with "[Q<id>]", the app's permanent question
id, so the response sheet can be scored with the same ids as the in-app form.
"""

import json
import sys

form = json.load(open(sys.argv[1]))
labels = form["scale"]["labels"]
questions = form["questions"]

INTRO = (
    "Khoảng 5 phút. Bác sĩ chấm từng mặt của kết quả AI: vùng tô, điểm chẩn "
    "đoán của cả 11 nhãn, khi AI sai, cách trình bày (1 = rất kém · 5 = rất tốt).\n"
    "Không có câu trả lời đúng hay sai. Đánh giá thấp cũng có ích như đánh giá cao.\n"
    "Phiếu này trả lời MỘT LẦN, sau khi xem xong các ca mẫu, không phải cho từng ca.\n"
    "Câu có dấu * là bắt buộc. Các câu khác bác sĩ trả lời nếu muốn."
)

lines = []
emit = lines.append
emit("// Generated by tools/google_form/build_form_script.py -- do not edit by hand.")
emit("// Paste into https://script.google.com, then Run > createSurveyForm.")
emit("// It creates the Form and a linked response Sheet in your Drive, and")
emit("// logs three links (View > Logs): the Form to send, the Form editor,")
emit("// and the prefill link the app uses to fill in the room name.")
emit("function createSurveyForm() {")
emit(f"  var LABELS = {json.dumps(labels, ensure_ascii=False)};")
emit("  var form = FormApp.create('Phiếu đánh giá phần mềm Spine Labeling');")
emit(f"  form.setDescription({json.dumps(INTRO, ensure_ascii=False)});")
emit("  form.setCollectEmail(false);")
emit("  form.setProgressBar(true);")
emit("  form.setConfirmationMessage('Cảm ơn bác sĩ đã dành thời gian đánh giá!');")
emit("")
emit("  // Ties this answer to the room's corrections in the app. Filled in")
emit("  // automatically when the doctor opens the form from the app.")
emit("  var room = form.addTextItem()")
emit("    .setTitle('Phòng của bác sĩ trên trang web')")
emit("    .setHelpText('Tên phòng ghi ở góc trên trang web. Mở phiếu từ nút ★ trên trang web thì ô này tự điền sẵn.')")
emit("    .setRequired(true);")
emit("")
emit("  function scale(title, id, required) {")
emit("    form.addScaleItem().setTitle(title).setHelpText('[Q' + id + ']')")
emit("      .setBounds(1, 5).setLabels(LABELS[0], LABELS[4]).setRequired(required);")
emit("  }")

first = True
for sec in form["sections"]:
    if first:
        emit(f"  form.addSectionHeaderItem().setTitle({json.dumps(sec['title'], ensure_ascii=False)});")
        first = False
    else:
        emit(f"  form.addPageBreakItem().setTitle({json.dumps(sec['title'], ensure_ascii=False)});")
    for group in sec["groups"]:
        in_group = [q for q in questions if q["group"] == group]
        matrix = [q for q in in_group if q["matrix"]]
        plain = [q for q in in_group if not q["matrix"]]
        emit(f"  form.addSectionHeaderItem().setTitle({json.dumps(group, ensure_ascii=False)});")
        for q in plain:
            emit(f"  scale({json.dumps(q['text'], ensure_ascii=False)}, {q['id']}, {str(q['required']).lower()});")
        if matrix:
            rows = [q["text"] for q in matrix]
            ids = ",".join(f"Q{q['id']}" for q in matrix)
            cols = [f"{i + 1} · {lab}" for i, lab in enumerate(labels)]
            emit("  form.addGridItem().setTitle('Độ chính xác theo từng nhãn')")
            emit(f"    .setHelpText('Bỏ trống nhãn nào bác sĩ không chắc. [{ids}]')")
            emit(f"    .setRows({json.dumps(rows, ensure_ascii=False)})")
            emit(f"    .setColumns({json.dumps(cols, ensure_ascii=False)});")

emit("  form.addPageBreakItem().setTitle('Góp ý và thông tin người đánh giá');")
emit("  form.addParagraphTextItem().setTitle('Bác sĩ có góp ý gì thêm cho phần mềm không?')")
emit("    .setHelpText('Ví dụ: ca nào AI chấm sai, chỗ nào khó dùng hay khó hiểu, cần thêm tính năng gì...');")
emit("  form.addTextItem().setTitle('Họ tên (có thể để trống)')")
emit("    .setHelpText('Không bắt buộc. Để trống thì phiếu ẩn danh.');")
emit("  form.addTextItem().setTitle('Chuyên khoa / vị trí (có thể để trống)');")
emit("")
emit("  var sheet = SpreadsheetApp.create('Phiếu đánh giá Spine Labeling (câu trả lời)');")
emit("  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());")
emit("  var prefill = form.createResponse()")
emit("    .withItemResponse(room.asTextItem().createResponse('ROOM_NAME'))")
emit("    .toPrefilledUrl();")
emit("  Logger.log('Form to send:   ' + form.getPublishedUrl());")
emit("  Logger.log('Form editor:    ' + form.getEditUrl());")
emit("  Logger.log('Responses sheet: ' + sheet.getUrl());")
emit("  Logger.log('Prefill link (give this one to Claude): ' + prefill);")
emit("}")
print("\n".join(lines))
